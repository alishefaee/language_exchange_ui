export const ApiStatus = {
  OK: 1000,
  CREATED: 1001,
  FORBIDDEN: 2001,
  AUTH_TOKEN_EXPIRED: 2004,
  VALIDATION_FAILED: 3001,
  RESOURCE_NOT_FOUND: 3002,
} as const;

export type ApiStatus = (typeof ApiStatus)[keyof typeof ApiStatus];

export interface ApiResponse<T = unknown> {
  status: ApiStatus;
  message?: string;
  data: T;
}

export type OnboardingStep =
  | "demographics"
  | "geography"
  | "languages"
  | "bio_avatar"
  | "completed";

export interface IUser {
  id: string;
  username: string; // Auto-generated by backend (e.g., user91879756)
  email: string;
  onboardingStep: OnboardingStep;
  avatarUrl?: string;
  lastLogin?: string;
  lastUpdatedProfile?: string;
}

export interface AuthTokens {
  accessToken: string;
  refreshToken: string;
}

export interface AuthPayload extends AuthTokens {
  user: IUser;
}

export class ApiError extends Error {
  public status: ApiStatus;
  public httpStatus: number;
  public fieldErrors?: Record<string, string[]>;

  constructor(
    message: string,
    status: ApiStatus,
    httpStatus: number,
    fieldErrors?: Record<string, string[]>
  ) {
    super(message);
    this.name = "ApiError";
    this.status = status;
    this.httpStatus = httpStatus;
    this.fieldErrors = fieldErrors;
  }
}